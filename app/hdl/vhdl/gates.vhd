-- VHDL Entity and Architecture: Logic Gates
library IEEE;
use IEEE.STD_LOGIC_1164.ALL;

entity vhdl_basic_gates is
    port (a, b : in std_logic; y_nand, y_nor, y_xor : out std_logic);
end entity;

architecture behavioral of vhdl_basic_gates is
begin
    y_nand <= not (a and b);
    y_nor  <= not (a or b);
    y_xor  <= a xor b;
end architecture;
